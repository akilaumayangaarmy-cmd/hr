import { quoteIdent } from './identifiers';
import { ColumnDef, TableDef } from './types';
import { typeLabel } from './labels';

export function renderLookupDdl(tables: TableDef[]): string {
  const blocks = tables
    .filter((table) => table.surrogateKey && !table.quoteIdentifiers)
    .map((table) => renderTable(table));
  return `-- Generated from backend/src/metadata/table-registry.ts
-- Re-run: npm run ddl --prefix backend
-- Safe to re-run: an existing table name is left unchanged.
-- Identifiers are unquoted and stored in uppercase.
-- old_id is the upsert key. id is a VARCHAR2(36) primary key generated by the loader.
-- Foreign keys are omitted so reference data can be loaded in any order.

${blocks.join('\n')}
`;
}

function renderTable(table: TableDef): string {
  const columns = table.columns
    .map((column) => `      ${columnSql(table, column)}`)
    .join(',\n');
  const pk = `PK_${table.physicalName}`;
  const uq = `UQ_${table.physicalName}_OLD_ID`;
  const surrogate = table.columns.find((column) => column.name === table.surrogateKey);
  const business = table.columns.find((column) => column.name === table.businessKey);
  if (!surrogate || !business) throw new Error(`Lookup table ${table.key} is missing its keys`);
  const body = `CREATE TABLE ${quoteIdent(false, table.physicalName)} (
${columns},
      CONSTRAINT ${pk} PRIMARY KEY (${quoteIdent(false, surrogate.physicalName)}),
      CONSTRAINT ${uq} UNIQUE (${quoteIdent(false, business.physicalName)})
    )`;
  return `BEGIN
  EXECUTE IMMEDIATE q'[
    ${body}
  ]';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN
      RAISE;
    END IF;
END;
/
`;
}

function columnSql(table: TableDef, column: ColumnDef): string {
  const parts = [quoteIdent(table.quoteIdentifiers, column.physicalName), sqlType(column)];
  if (column.databaseDefault !== undefined) {
    if (!Number.isSafeInteger(column.databaseDefault)) throw new Error(`Bad default for ${column.name}`);
    parts.push(`DEFAULT ${column.databaseDefault}`);
  }
  if (!column.nullable) parts.push('NOT NULL');
  return parts.join(' ');
}

function sqlType(column: ColumnDef): string {
  const label = typeLabel(column);
  if (column.type === 'number' && label === 'NUMBER') return 'NUMBER';
  return label;
}
